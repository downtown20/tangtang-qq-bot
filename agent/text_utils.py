"""
中文文本匹配工具 —— 解决子串匹配在中文里的系统性假阳性问题

问题：「亲」in「亲自去一趟」→ True（假阳性）
解法：要求关键词前后必须是词边界（标点/空格/字符串边界/其他语义边界）

用法：替换所有 `keyword in text` 为 `word_match(text, keyword)`
"""
import re


# 常见误匹配复合词黑名单——单字关键词在这些词里不是独立语义单元
# 「抱歉」含「抱」但「抱」不是独立的 → 不匹配
# 「亲一个」→「亲」独立 → 不在黑名单中 → 匹配
_COMPOUND_BLACKLIST: dict[str, set[str]] = {
    "抱": {"抱歉", "拥抱", "怀抱", "抱怨", "抱负", "搂抱", "环抱"},
    "亲": {"亲自", "父亲", "母亲", "亲戚", "亲友", "亲爱", "亲密", "亲吻", "双亲", "探亲", "相亲", "亲王"},
    "骚": {"骚扰", "风骚", "离骚"},
    "猫": {"猫娘", "猫咪", "猫腻", "熊猫", "山猫", "狸猫", "野猫"},
    "狗": {"狗血", "热狗", "狗屁", "狗粮", "狗腿", "狗头", "小狗", "狼狗"},
    "哭": {"哭笑不得", "哭泣", "痛哭"},
    "累": {"积累", "累计", "累积", "连累", "拖累", "受累", "劳累"},
    "烦": {"麻烦", "烦恼", "不耐烦", "烦躁", "烦人"},
    "滚": {"翻滚", "打滚"},
    "牛": {"牛奶", "牛肉", "奶牛", "黄牛", "蜗牛"},
    "好": {"你好", "好像", "还好", "刚好", "正好", "美好", "良好", "最好", "只好"},
    "行": {"银行", "旅行", "不行", "还行", "进行", "流行", "执行", "运行"},
    "怕": {"可怕", "害怕", "哪怕", "恐怕", "惧怕"},
    "笑": {"开玩笑", "搞笑", "笑容", "笑声", "笑话", "微笑", "嘲笑", "大笑"},
    "泪": {"眼泪", "泪水", "落泪", "含泪", "流泪"},
    "歌": {"唱歌", "歌词", "歌曲", "歌手", "诗歌", "颂歌", "赞歌", "儿歌", "国歌"},
    "吃": {"好吃", "吃饭", "吃惊", "吃亏", "小吃", "吃醋", "吃亏", "口吃"},
    "爱": {"可爱", "爱情", "恋爱", "喜爱", "热爱", "友爱", "亲爱"},
}


def word_match(text: str, keyword: str) -> bool:
    """检查 keyword 是否作为独立语义单元出现在 text 中。
    双字及以上关键词直接用 `in`——假阳性极低。
    单字关键词用复合词黑名单过滤——「抱歉」含「抱」但不匹配，「亲一个」→「亲」独立→匹配。"""
    if len(keyword) >= 2:
        return keyword in text

    # 单字关键词：排除黑名单中的复合词后，检查剩余出现
    blacklist = _COMPOUND_BLACKLIST.get(keyword, set())
    if blacklist:
        # 用占位符替换掉所有黑名单复合词，再检查剩余
        filtered = text
        for compound in blacklist:
            filtered = filtered.replace(compound, "█" * len(compound))
        if keyword in filtered:
            return True
        return False

    # 没有黑名单的关键词 → 直接用 in（假阳性风险低）
    return keyword in text

